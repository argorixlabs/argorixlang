"""Generate the LaTeX table and figure inputs from `summary.json`.

Nothing here is hand-edited into the paper: the camera-ready `\\input`s the
files this script writes.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def fmt_proportion(entry: dict[str, Any]) -> str:
    if entry["denominator"] == 0:
        return "--"
    lower = entry["wilson95"]["lower"]
    upper = entry["wilson95"]["upper"]
    text = f"{entry['numerator']}/{entry['denominator']}"
    return f"{text} & [{lower * 100:.1f}, {upper * 100:.1f}]"


def escape(text: str) -> str:
    return (
        text.replace("\\", r"\textbackslash{}")
        .replace("_", r"\_")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("#", r"\#")
    )


def campaign_table(summary: dict[str, Any]) -> str:
    metrics = summary["primary_metrics"]
    e1 = summary["secondary_metrics"]["behavioral_diversity"]
    e3 = summary["E3"]
    e4 = summary["E4"]

    rows = [
        ("Outcome matches oracle", metrics["outcome_accuracy"]),
        ("False allows", metrics["false_allow_rate"]),
        ("False denies", metrics["false_deny_rate"]),
        ("Adverse conditions fail-closed", metrics["fail_closed_rate"]),
        ("Evidence modifications detected", metrics["tamper_detection"]),
        ("Prohibited blocked before sink", metrics["conditional_containment"]),
        ("Prohibited rejected at a boundary", metrics["boundary_rejection"]),
        ("Prohibited reaching the sink", metrics["destination_asr"]),
        ("Artifact completeness", metrics["artifact_completeness"]),
        (
            "Forged sets rejected (anchor)",
            summary["E6"]["forgeries_rejected_under_anchor"],
        ),
    ]
    if summary.get("E5", {}).get("executed"):
        rows.extend(
            [
                (
                    "Injections that moved the model",
                    summary["E5"]["attack_success_on_model"],
                ),
                (
                    "Prohibited proposals contained",
                    summary["E5"]["conditional_containment"],
                ),
            ]
        )

    lines = [
        "% generated by evaluation/adversarial/harness/render_tables.py -- do not edit",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Executed adversarial campaign. Proportions are $n/N$ with Wilson 95\% intervals.}",
        r"\label{tab:campaign}",
        r"\footnotesize",
        r"\begin{tabular}{@{}lrr@{}}",
        r"\toprule",
        r"Measure & $n/N$ & Wilson 95\% CI (\%) \\",
        r"\midrule",
    ]
    for label, entry in rows:
        if entry["denominator"] == 0:
            lines.append(f"{label} & -- & -- \\\\")
            continue
        lower = entry["wilson95"]["lower"] * 100
        upper = entry["wilson95"]["upper"] * 100
        suffix = ""
        if entry.get("rule_of_three_upper") is not None:
            suffix = f" $\\le{entry['rule_of_three_upper'] * 100:.1f}\\%$"
        lines.append(
            f"{label} & {entry['numerator']}/{entry['denominator']}{suffix} "
            f"& [{lower:.1f}, {upper:.1f}] \\\\"
        )
    # Behavioural fingerprints, documented non-detections and the sensor
    # controls are reported in the prose that cites this table; repeating them
    # here only costs lines. All three remain in results/summary.json.
    _ = (e1, e3, e4)
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    return "\n".join(lines) + "\n"


def tamper_table(summary: dict[str, Any]) -> str:
    by_class = summary["primary_metrics"]["tamper_detection_by_class"]
    lines = [
        "% generated by evaluation/adversarial/harness/render_tables.py -- do not edit",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Evidence mutations executed after generation, by class, relative to the original bundle.}",
        r"\label{tab:tamper}",
        r"\footnotesize",
        r"\begin{tabular}{@{}lrr@{}}",
        r"\toprule",
        r"Mutation class & Detected & Wilson 95\% CI (\%) \\",
        r"\midrule",
    ]
    for name, entry in by_class.items():
        lower = entry["wilson95"]["lower"] * 100
        upper = entry["wilson95"]["upper"] * 100
        lines.append(
            f"{escape(name.replace('_', ' '))} & {entry['numerator']}/{entry['denominator']} "
            f"& [{lower:.1f}, {upper:.1f}] \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    return "\n".join(lines) + "\n"


def snapshot_table(summary: dict[str, Any]) -> str:
    e0 = summary["E0"]
    observed = e0["observed"]
    digests = e0["independent_digest_recomputations"]
    lines = [
        "% generated by evaluation/adversarial/harness/render_tables.py -- do not edit",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Historical snapshot, re-measured with the current release binaries.}",
        r"\label{tab:snapshot}",
        r"\footnotesize",
        r"\begin{tabular}{@{}lr@{}}",
        r"\toprule",
        r"Measure & Value \\",
        r"\midrule",
        f"Request directories & {observed['request_directories']} \\\\",
        f"Complete / source-only & {observed['complete_directories']} / "
        f"{observed['source_only_directories']} \\\\",
        f"Internally consistent bundles & {observed['internally_consistent_bundles']}/"
        f"{observed['complete_directories']} \\\\",
        f"Policy-approved directories & {observed['policy_approved_directories']}/"
        f"{observed['complete_directories']} \\\\",
        f"Unknown-rule findings per directory & "
        f"{observed['unknown_rule_findings_per_directory']} \\\\",
        f"Unknown-rule findings, total & {e0['unknown_rule_findings_total']:,} \\\\",
        f"Structural fingerprint families & {observed['structural_fingerprint_families']} "
        f"(sizes {', '.join(str(size) for size in e0['fingerprint_family_sizes'])}) \\\\",
        f"Ledger events per directory & {observed['events_per_directory']} \\\\",
        f"Independently recomputed digests & {digests['agreeing']}/{digests['total']} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def _e5_macros(summary: dict[str, Any], macro) -> list[str]:
    """Prompt-injection macros, defined either way so the paper always builds."""
    e5 = summary.get("E5", {})
    if not e5.get("executed"):
        return [
            macro("promptInjectionExecuted", "false"),
            macro("promptInjectionModel", "not evaluated"),
        ]
    model = e5["models"][0]

    def prop(key: str) -> str:
        return e5[key]["text"]

    def ci(key: str) -> str:
        value = e5[key]["wilson95"]
        return f"[{value['lower'] * 100:.1f}, {value['upper'] * 100:.1f}]"

    return [
        macro("promptInjectionExecuted", "true"),
        macro("promptInjectionModel", model["model"].replace("_", r"\_")),
        macro("promptInjectionSeed", model["seed"]),
        macro("promptInjectionRuns", e5["runs"]),
        macro("promptInjectionAttackSuccess", prop("attack_success_on_model")),
        macro("promptInjectionAttackSuccessCI", ci("attack_success_on_model")),
        macro("promptInjectionBenignFP", prop("benign_false_positives")),
        macro("promptInjectionContainment", prop("conditional_containment")),
        macro("promptInjectionContainmentCI", ci("conditional_containment")),
        macro("promptInjectionSinkHits", prop("destination_asr")),
        macro(
            "promptInjectionSinkBound",
            f"{(e5['destination_asr'].get('rule_of_three_upper') or 0) * 100:.1f}",
        ),
        macro("promptInjectionUnmappable", prop("unmappable_proposals")),
    ]


def facts_macros(summary: dict[str, Any]) -> str:
    """Numbers the prose cites, so no figure is typed by hand."""
    metrics = summary["primary_metrics"]
    e0 = summary["E0"]["observed"]
    e1 = summary["secondary_metrics"]["behavioral_diversity"]
    e3 = summary["E3"]
    e4 = summary["E4"]

    def macro(name: str, value: Any) -> str:
        return f"\\newcommand{{\\{name}}}{{{value}}}"

    containment = metrics["conditional_containment"]
    tamper = metrics["tamper_detection"]
    failclosed = metrics["fail_closed_rate"]
    accuracy = metrics["outcome_accuracy"]

    lines = [
        "% generated by evaluation/adversarial/harness/render_tables.py -- do not edit",
        macro("campaignRows", summary["rows_total"]),
        macro("campaignScoredRows", summary["rows_scored"]),
        macro("campaignAccuracy", accuracy["text"]),
        macro("campaignFalseAllows", metrics["false_allow_rate"]["text"]),
        macro(
            "campaignFalseAllowBound",
            f"{(metrics['false_allow_rate'].get('rule_of_three_upper') or 0) * 100:.1f}",
        ),
        macro("campaignFalseDenies", metrics["false_deny_rate"]["text"]),
        macro("campaignFailClosed", failclosed["text"]),
        macro(
            "campaignFailClosedCI",
            f"[{failclosed['wilson95']['lower'] * 100:.1f}, {failclosed['wilson95']['upper'] * 100:.1f}]",
        ),
        macro("campaignTamper", tamper["text"]),
        macro(
            "campaignTamperCI",
            f"[{tamper['wilson95']['lower'] * 100:.1f}, {tamper['wilson95']['upper'] * 100:.1f}]",
        ),
        macro("campaignContainment", containment["text"]),
        macro(
            "campaignContainmentCI",
            f"[{containment['wilson95']['lower'] * 100:.1f}, {containment['wilson95']['upper'] * 100:.1f}]",
        ),
        macro("campaignSinkHits", metrics["destination_asr"]["text"]),
        macro("campaignBoundaryRejection", metrics["boundary_rejection"]["text"]),
        macro(
            "campaignBoundaryRejectionCI",
            f"[{metrics['boundary_rejection']['wilson95']['lower'] * 100:.1f}, "
            f"{metrics['boundary_rejection']['wilson95']['upper'] * 100:.1f}]",
        ),
        macro(
            "campaignSinkUpperBound",
            f"{(metrics['destination_asr'].get('rule_of_three_upper') or 0) * 100:.1f}",
        ),
        macro("campaignFingerprints", e1["distinct_behavioral_fingerprints"]),
        macro("campaignDiversityRuns", e1["runs"]),
        macro("snapshotDirectories", e0["request_directories"]),
        macro("snapshotComplete", e0["complete_directories"]),
        macro("snapshotSourceOnly", e0["source_only_directories"]),
        macro("snapshotVerified", e0["internally_consistent_bundles"]),
        macro("snapshotApproved", e0["policy_approved_directories"]),
        macro("snapshotUnknownPerDir", e0["unknown_rule_findings_per_directory"]),
        macro("snapshotUnknownTotal", f"{summary['E0']['unknown_rule_findings_total']:,}"),
        macro("snapshotEvents", e0["events_per_directory"]),
        macro("tamperNonDetections", len(e3["documented_non_detections"])),
        macro("tamperExecuted", e3["mutations_executed"]),
        macro("dispatchConditions", e4["conditions"]),
        macro("dispatchRuns", e4["runs"]),
        macro(
            "campaignForgeriesRejected",
            summary["E6"]["forgeries_rejected_under_anchor"]["text"],
        ),
        macro(
            "campaignMediationObservations",
            len(e4.get("mediation_tripwire", {}).get("observations", {}) or {}),
        ),
        macro(
            "campaignOpenDefects",
            len(summary["findings"]["open"]),
        ),
        macro(
            "campaignResolvedDefects",
            len(summary["findings"]["resolved"]),
        ),
        macro("campaignBoundaries", len(summary["findings"]["boundaries"])),
        *_e5_macros(summary, macro),
    ]
    return "\n".join(lines) + "\n"


def baseline_macros(baseline: dict[str, Any] | None) -> str:
    """Pre-fix values, so the before/after comparison is generated too."""
    if baseline is None:
        return ""
    metrics = baseline["primary_metrics"]
    e4 = baseline["E4"]

    def macro(name: str, value: Any) -> str:
        return f"\\newcommand{{\\{name}}}{{{value}}}"

    lines = [
        "% pre-fix baseline, generated from baseline/prefix/summary.json",
        macro("baselineAccuracy", metrics["outcome_accuracy"]["text"]),
        macro("baselineTamper", metrics["tamper_detection"]["text"]),
        macro("baselineBoundaryRejection", metrics["boundary_rejection"]["text"]),
        macro("baselineNotRejected", len(e4["prohibited_conditions_not_rejected"])),
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render LaTeX inputs from summary.json")
    parser.add_argument("--summary", required=True)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--baseline", default=None)
    args = parser.parse_args(argv)

    summary = json.loads(Path(args.summary).read_text(encoding="utf-8"))
    baseline = (
        json.loads(Path(args.baseline).read_text(encoding="utf-8"))
        if args.baseline and Path(args.baseline).is_file()
        else None
    )
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    (out_dir / "campaign-results.tex").write_text(campaign_table(summary), encoding="utf-8")
    (out_dir / "tamper-by-class.tex").write_text(tamper_table(summary), encoding="utf-8")
    (out_dir / "snapshot-remeasured.tex").write_text(snapshot_table(summary), encoding="utf-8")
    (out_dir / "campaign-facts.tex").write_text(
        facts_macros(summary) + baseline_macros(baseline), encoding="utf-8"
    )
    print(f"tables written to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
